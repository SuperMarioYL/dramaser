#!/usr/bin/env python3
"""Construct README/website SVG artwork from authored facts and the renderer palette.

Reads docs/presentation.json (authored facts), web/palette.json (generated by the
pinned web-factory renderer from web/site.json) and docs/demo-results.json (the
verified demo record) and writes:

- the four animated light/dark SVG groups — hero, architecture, process,
  integrations — in desktop and mobile compositions to assets/presentation/
  and web/assets/presentation/;
- the website-only stills — the neon-graph static scene fallbacks and the
  recorded-demo score chart — to web/assets/.

The complete static frame (labels, relationships, results) is preserved with
animations disabled; a reduced-motion media query stops decorative movement.
Scene fallbacks are fully static stills. Every chart number comes from
docs/demo-results.json; nothing is invented here.
"""

import json
import math
import random
import shutil
import textwrap
from html import escape
from pathlib import Path


def local(value):
    return (
        str(value.get("en") or value.get("zh") or "")
        if isinstance(value, dict)
        else str(value or "")
    )


def render_site_artwork(repo: Path, palette: dict) -> None:
    """Website-only stills: the neon-graph static fallbacks and the demo score chart.

    The scene fallback mirrors the renderer's hero particle graph as a complete
    static still (no animation at all — a reduced-motion switch alone is not a
    static fallback). The chart plots only the numbers recorded in
    docs/demo-results.json: per-shot replay scores for both lanes and the gate
    threshold; the drifted/locked counts are derived from those scores.
    """
    record = json.loads((repo / "docs/demo-results.json").read_text())
    threshold = float(record["threshold"])
    drift = record["scores"]["drift"]
    locked = record["scores"]["locked"]
    shots = sorted(drift)
    drifted = sum(1 for s in shots if drift[s] < threshold)
    held = sum(1 for s in shots if locked[s] >= threshold)
    web_assets = repo / "web/assets"
    web_assets.mkdir(parents=True, exist_ok=True)
    sans = "Arial,&quot;Noto Sans&quot;,sans-serif"
    mono = "ui-monospace,Menlo,Consolas,monospace"

    def save_still(slug, w, h, title, description, body):
        svg = (
            f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}"'
            f' viewBox="0 0 {w} {h}" data-palette="{palette["id"]}" role="img"'
            f' aria-labelledby="{slug}-title {slug}-desc"><title id="{slug}-title">'
            f'{escape(title)}</title><desc id="{slug}-desc">{escape(description)}'
            f"</desc>{body}</svg>\n"
        )
        (web_assets / f"{slug}.svg").write_text(svg)

    for mode in ("dark", "light"):
        p = palette[mode]

        # -- static neon-graph still (hero scene fallback) ---------------
        rng = random.Random("dramaser-scene")
        cx, cy, rx, ry = 400, 198, 336, 126
        pts = []
        body = f'<rect width="800" height="400" fill="{p["bg"]}"/>'
        for i in range(260):
            a = rng.random() * math.tau
            z = rng.uniform(-1, 1)
            r = math.sqrt(1 - z * z)
            ripple = 1 + 0.05 * math.sin(a * 8 + z * 7)
            x = cx + rx * r * math.cos(a) * ripple
            y = cy + ry * z * ripple
            pts.append((x, y))
            body += (
                f'<circle cx="{x:.1f}" cy="{y:.1f}" r="{rng.uniform(0.7, 1.9):.2f}"'
                f' fill="{p["primary"] if i % 3 else p["secondary"]}"'
                f' opacity="{rng.uniform(0.18, 0.72):.2f}"/>'
            )
        links = 0
        for i, (x, y) in enumerate(pts):
            for j in range(i):
                if links >= 110:
                    break
                qx, qy = pts[j]
                if (x - qx) ** 2 + (y - qy) ** 2 < 2100:
                    body += (
                        f'<line x1="{x:.1f}" y1="{y:.1f}" x2="{qx:.1f}" y2="{qy:.1f}"'
                        f' stroke="{p["secondary"]}" stroke-opacity=".14"/>'
                    )
                    links += 1
        chain = [(122, 240), (302, 150), (506, 188), (684, 116)]
        body += (
            '<defs><filter id="glow"><feGaussianBlur stdDeviation="4"/></filter></defs>'
            '<polyline points="'
            + " ".join(f"{x},{y}" for x, y in chain)
            + f'" fill="none" stroke="{p["highlight"]}" stroke-width="1.6"'
            ' stroke-opacity=".65"/>'
        )
        for k, (x, y) in enumerate(chain):
            halo = 9 if k == 2 else 6
            body += (
                f'<circle cx="{x}" cy="{y}" r="{halo}" fill="{p["highlight"]}"'
                f' opacity=".3" filter="url(#glow)"/><circle cx="{x}" cy="{y}" r="4"'
                f' fill="{p["bg"]}" stroke="{p["highlight"]}" stroke-width="1.6"/>'
                f'<circle cx="{x}" cy="{y}" r="1.6" fill="{p["highlight"]}"/>'
            )
        save_still(
            f"scene-{mode}",
            800,
            400,
            "dramaser particle scene",
            "Static still of the illustrative neon-graph hero scene.",
            body,
        )

        # -- recorded demo score chart ----------------------------------
        x0, x1, ytop, ybase, lo, hi = 66, 722, 84, 236, 0.40, 1.02

        def py(v):
            return ybase - (v - lo) / (hi - lo) * (ybase - ytop)

        def px(i):
            return x0 + i * (x1 - x0) / (len(shots) - 1)

        b = (
            f'<rect width="760" height="300" rx="14" fill="{p["bg"]}"/>'
            f'<text x="28" y="40" fill="{p["ink"]}" font-family="{sans}"'
            ' font-size="14" font-weight="600">replay consistency scores</text>'
            f'<text x="732" y="40" text-anchor="end" fill="{p["muted"]}"'
            f' font-family="{mono}" font-size="11">replay mode · no API key</text>'
            f'<line x1="360" y1="58" x2="380" y2="58" stroke="{p["secondary"]}"'
            ' stroke-width="2.5"/>'
            f'<text x="386" y="62" fill="{p["secondary"]}" font-family="{mono}"'
            f' font-size="11">unlocked · {drifted}/{len(shots)} drifted</text>'
            f'<line x1="556" y1="58" x2="576" y2="58" stroke="{p["primary"]}"'
            ' stroke-width="2.5"/>'
            f'<text x="582" y="62" fill="{p["primary"]}" font-family="{mono}"'
            f' font-size="11">locked · {held}/{len(shots)}</text>'
        )
        for v in (0.5, 0.6, 0.7, 0.8, 0.9, 1.0):
            b += (
                f'<line x1="{x0}" y1="{py(v):.1f}" x2="{x1}" y2="{py(v):.1f}"'
                f' stroke="{p["line"]}" stroke-width="1"/>'
                f'<text x="{x0 - 8}" y="{py(v) + 3.5:.1f}" text-anchor="end"'
                f' fill="{p["muted"]}" font-family="{mono}" font-size="10">{v:.1f}</text>'
            )
        b += (
            f'<line x1="{x0}" y1="{py(threshold):.1f}" x2="{x1}"'
            f' y2="{py(threshold):.1f}" stroke="{p["highlight"]}" stroke-width="1.4"'
            ' stroke-dasharray="6 5"/>'
            f'<text x="{x1}" y="{py(threshold) - 6:.1f}" text-anchor="end"'
            f' fill="{p["highlight"]}" font-family="{mono}" font-size="10.5">'
            f"gate {threshold:.2f}</text>"
        )
        b += (
            '<polyline points="'
            + " ".join(f"{px(i):.1f},{py(locked[s]):.1f}" for i, s in enumerate(shots))
            + f'" fill="none" stroke="{p["primary"]}" stroke-width="2.5"'
            ' stroke-linecap="round" stroke-linejoin="round"/>'
            '<polyline points="'
            + " ".join(f"{px(i):.1f},{py(drift[s]):.1f}" for i, s in enumerate(shots))
            + f'" fill="none" stroke="{p["secondary"]}" stroke-width="2.5"'
            ' stroke-linecap="round" stroke-linejoin="round"/>'
        )
        for i, s in enumerate(shots):
            x = px(i)
            b += (
                f'<circle cx="{x:.1f}" cy="{py(locked[s]):.1f}" r="3.2"'
                f' fill="{p["bg"]}" stroke="{p["primary"]}" stroke-width="1.8"/>'
            )
            below = drift[s] < threshold
            b += (
                f'<circle cx="{x:.1f}" cy="{py(drift[s]):.1f}" r="3.4"'
                f' fill="{p["secondary"] if below else p["bg"]}"'
                f' stroke="{p["secondary"]}" stroke-width="1.8"/>'
            )
        # Ep01's unlocked scores (0.99) sit visually on the locked line, so
        # per-point value labels would collide; label one group mean instead.
        episodes = []
        for gi in range(0, len(shots), 3):
            group = shots[gi : gi + 3]
            episodes.append(group[0].split("_")[0])
            mean = sum(drift[s] for s in group) / len(group)
            mid = px(gi + 1)
            b += (
                f'<text x="{mid:.1f}" y="{py(mean) + 18:.1f}" text-anchor="middle"'
                f' fill="{p["muted"]}" font-family="{mono}" font-size="10">'
                f"{mean:.2f}</text>"
                f'<text x="{mid:.1f}" y="272" text-anchor="middle"'
                f' fill="{p["ink"]}" font-family="{sans}" font-size="12"'
                f' font-weight="600">{episodes[-1]}</text>'
            )
        for i, s in enumerate(shots):
            b += (
                f'<text x="{px(i):.1f}" y="254" text-anchor="middle"'
                f' fill="{p["muted"]}" font-family="{mono}" font-size="10">'
                f'{s.split("_")[1]}</text>'
            )
        b += (
            f'<text x="{px(0):.1f}" y="{py(1.0) - 9:.1f}" fill="{p["muted"]}"'
            f' font-family="{mono}" font-size="10">1.00</text>'
        )
        save_still(
            f"demo-scores-{mode}",
            760,
            300,
            "dramaser replay consistency — unlocked drift vs locked",
            f"Recorded replay scores for {len(shots)} shots across "
            f"{len(episodes)} episodes: the unlocked lane drifts below the "
            f"{threshold:.2f} gate on {drifted} shots, the locked lane holds "
            f"{held}/{len(shots)}.",
            b,
        )


def render(repo: Path) -> None:
    facts = json.loads((repo / "docs/presentation.json").read_text())
    palette = json.loads((repo / "web/palette.json").read_text())
    name = facts["name"]
    tagline = facts["tagline"]
    nodes = facts["architecture"]["nodes"]
    edges = facts["architecture"]["edges"]
    assert (
        3 <= len(nodes) <= 6
        and 3 <= len(facts["process"]["steps"]) <= 4
        and 3 <= len(facts["integrations"]["items"]) <= 6
    )
    assert all(0 <= int(e[0]) < len(nodes) and 0 <= int(e[1]) < len(nodes) for e in edges)
    folder = repo / "assets/presentation"
    web = repo / "web/assets/presentation"
    folder.mkdir(parents=True, exist_ok=True)
    web.mkdir(parents=True, exist_ok=True)

    def render_mode(mode):
        p = palette[mode]

        def txt(x, y, s, size=20, color="ink", anchor="start", weight=400):
            return (
                f'<text x="{x}" y="{y}" fill="{p[color]}" font-size="{size}" text-anchor="'
                f'{anchor}" font-weight="{weight}">{escape(local(s))}</text>'
            )

        def para(x, y, s, width, size=18, color="muted", limit=3, anchor="start"):
            rows = textwrap.wrap(local(s), max(8, int(width / (size * 0.57)))) or [""]
            if len(rows) > limit:
                rows = rows[:limit]
                rows[-1] = rows[-1].rstrip(".") + "…"
            return "".join(
                txt(x, y + i * size * 1.4, t, size, color, anchor) for i, t in enumerate(rows)
            )

        def line(d, active=True):
            return (
                f'<path d="{d}" fill="none" stroke="'
                f"{(p['primary'] if active else p['line'])}"
                '" stroke-width="1.5" marker-end="url(#arrow)"/>'
            ) + (
                (
                    f'<path d="{d}" class="flow" fill="none" stroke="{p["highlight"]}"'
                    ' stroke-width="2"/>'
                )
                if active
                else ""
            )

        def card(x, y, w, title, detail, h=122):
            return (
                f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="12" fill="'
                f'{p["panel"]}" stroke="{p["line"]}"/>'
                + para(x + 18, y + 31, title, w - 36, 21, "ink", 2)
                + para(x + 18, y + 83, detail, w - 36, 17, "muted", 2)
            )

        def particles(cx, cy, rx, ry, count=360):
            rng = random.Random(name)
            s = ""
            for i in range(count):
                a = rng.random() * math.tau
                z = rng.uniform(-1, 1)
                r = math.sqrt(1 - z * z)
                x = cx + rx * r * math.cos(a)
                y = cy + ry * z
                s += (
                    f'<circle cx="{x:.2f}" cy="{y:.2f}" r="{rng.uniform(0.6, 1.7):.2f}" fill="'
                    f'{(p["primary"] if i % 3 else p["secondary"])}" opacity="'
                    f'{rng.uniform(0.2, 0.8):.2f}"/>'
                )
            return s

        def save(kind, w, h, title, description, body, mobile=False):
            slug = f"{kind}{'-mobile' if mobile else ''}-{mode}"
            css = (
                'text{font-family:Arial,"Noto Sans",sans-serif}.flow{stroke-dasharray:10 110;'
                "animation:flow 6s linear infinite}.pulse{animation:pulse 5s ease-in-out"
                "infinite}.turn{transform-box:fill-box;transform-origin:center;animation:"
                "turn 36s linear infinite}@keyframes flow{to{stroke-dashoffset:-360}}"
                "@keyframes pulse{0%,100%{opacity:.45}50%{opacity:1}}@keyframes turn{to{"
                "transform:rotate(360deg)}}@media(prefers-reduced-motion:reduce){*{animation:"
                'none!important;transform:none!important}.flow{display:none}}'
            )
            svg = (
                f'<svg xmlns="http://www.w3.org/2000/svg" width="{w}" height="{h}'
                f'" viewBox="0 0 {w} {h}" data-palette="{palette["id"]}'
                f'" role="img" aria-labelledby="{slug}-title {slug}-desc"><title id="{slug}'
                f'-title">{escape(title)}</title><desc id="{slug}-desc">{escape(description)}'
                '</desc><defs><linearGradient id="brand" gradientUnits="userSpaceOnUse" x2="'
                f'{w}" y2="{h}"><stop stop-color="{p["primary"]}"/><stop offset=".6" '
                f'stop-color="{p["secondary"]}"/><stop offset="1" stop-color="{p["highlight"]}"'
                '/></linearGradient><radialGradient id="halo"><stop stop-color="'
                f'{p["primary"]}" stop-opacity=".22"/><stop offset="1" stop-color="'
                f'{p["bg"]}" stop-opacity="0"/></radialGradient><filter id="glow">'
                '<feGaussianBlur stdDeviation="5"/></filter><pattern id="grid" width="40" '
                f'height="40" patternUnits="userSpaceOnUse"><path d="M40 0H0V40" fill="none" '
                f'stroke="{p["line"]}" stroke-opacity=".35" stroke-width=".6"/></pattern>'
                '<marker id="arrow" viewBox="0 0 10 10" refX="8" refY="5" markerWidth="5" '
                'markerHeight="5" orient="auto"><path d="m1 1 7 4-7 4" fill="none" stroke="'
                f'{p["primary"]}" stroke-width="1.5"/></marker></defs><style>{css}</style>'
                f'<rect width="{w}" height="{h}" rx="16" fill="{p["bg"]}"/><rect width="{w}" '
                f'height="{h}" rx="16" fill="url(#grid)"/><ellipse cx="{w * 0.63}" '
                f'cy="{h * 0.43}" rx="{w * 0.5}" ry="{h * 0.7}" fill="url(#halo)"/>{body}</svg>'
            )
            out = folder / f"{slug}.svg"
            out.write_text(svg + "\n")
            shutil.copy2(out, web / out.name)

        for mobile in [False, True]:
            w = 400 if mobile else 1000
            # -- brand hero: particle convergence, neon name, one advantage ----
            cx, cy, rx, ry = (250, 362, 190, 140) if mobile else (825, 225, 260, 210)
            b = particles(cx, cy, rx, ry)
            b += txt(28 if mobile else 48, 50 if mobile else 56, "PROJECT / OPEN SOURCE", 13, "muted")
            size = min(46 if mobile else 74, (340 if mobile else 580) / max(1, len(name)) / 0.58)
            b += (
                f'<text x="{(28 if mobile else 48)}" y="{(117 if mobile else 182)}" font-size="'
                f'{size:.1f}" fill="url(#brand)" font-weight="700">{escape(name)}</text>'
            )
            b += para(
                28 if mobile else 50,
                163 if mobile else 242,
                tagline,
                340 if mobile else 530,
                21 if mobile else 24,
                "ink",
                3,
            )
            pts = [
                (cx - rx * 0.65, cy + ry * 0.4),
                (cx - rx * 0.24, cy - ry * 0.15),
                (cx + rx * 0.15, cy + ry * 0.05),
                (cx + rx * 0.58, cy - ry * 0.5),
            ]
            b += line("M" + "L".join(f"{x:.1f} {y:.1f}" for x, y in pts))
            for x, y in pts:
                b += (
                    f'<circle cx="{x}" cy="{y}" r="12" fill="{p["highlight"]}" opacity=".5" '
                    f'filter="url(#glow)"/><circle class="pulse" cx="{x}" cy="{y}" r="3" '
                    f'fill="{p["highlight"]}"/>'
                )
            save("hero", w, 510 if mobile else 390, name, tagline, b, mobile)

            # -- architecture: layered blueprint with real modules -------------
            h = 150 + len(nodes) * 145 if mobile else 570
            b = txt(28 if mobile else 44, 44, "ARCHITECTURE / DATA FLOW", 13, "muted") + para(
                28 if mobile else 44,
                84,
                facts["architecture"]["title"],
                344 if mobile else 900,
                25 if mobile else 30,
                "ink",
                2,
            )
            coords = (
                [(28, 130 + i * 145, 344) for i in range(len(nodes))]
                if mobile
                else [(44 + (i % 3) * 316, 142 + (i // 3) * 230, 276) for i in range(len(nodes))]
            )
            for k, e in enumerate(edges):
                a, t = map(int, e[:2])
                ax, ay, aw = coords[a]
                bx, by, bw = coords[t]
                if mobile:
                    if t == a + 1:
                        d = f"M{ax + aw / 2} {ay + 122}V{by}"
                    else:
                        d = f"M{ax + aw} {ay + 61}H{380 + k % 2 * 8}V{by + 61}H{bx + bw}"
                elif ay == by and abs(a - t) == 1:
                    d = f"M{ax + aw if bx > ax else ax} {ay + 61}H{bx if bx > ax else bx + bw}"
                else:
                    sy = ay + 122 if by > ay else ay
                    ty = by if by > ay else by + 122
                    lane = (sy + ty) / 2 + k % 3 * 8
                    if by == ay:
                        sy = ay + 122
                        ty = by + 122
                        lane = sy + 24 + k % 3 * 10
                    d = f"M{ax + aw / 2} {sy}V{lane}H{bx + bw / 2}V{ty}"
                b += line(d)
            for n, (x, y, cw) in zip(nodes, coords, strict=True):
                b += card(x, y, cw, n["title"], n["detail"])
            save("architecture", w, h, name + " architecture",
                 facts["architecture"]["title"], b, mobile)

            # -- process: ordered loop, regen touches only drifted work ---------
            steps = facts["process"]["steps"]
            h = 220 + len(steps) * 155 if mobile else 465
            b = txt(28 if mobile else 44, 44, "PROCESS / FROM LOCK TO DRAFT", 13, "muted") + para(
                28 if mobile else 44,
                84,
                facts["process"]["title"],
                344 if mobile else 900,
                25 if mobile else 30,
                "ink",
                2,
            )
            if mobile:
                for i, s in enumerate(steps):
                    y = 135 + i * 155
                    if i < len(steps) - 1:
                        b += line(f"M200 {y + 122}V{y + 155}")
                    b += card(28, y, 344, f"{i + 1:02}  " + s["title"], s["detail"])
                b += para(28, h - 65, facts["process"]["result"], 344, 18, "highlight", 2)
            else:
                cw = (912 - (len(steps) - 1) * 24) / len(steps)
                for i, s in enumerate(steps):
                    x = 44 + i * (cw + 24)
                    if i < len(steps) - 1:
                        b += line(f"M{x + cw} 237H{x + cw + 24}")
                    b += card(x, 176, cw, f"{i + 1:02}  " + s["title"], s["detail"])
                b += para(44, 379, facts["process"]["result"], 900, 20, "highlight", 2)
            save("process", w, h, name + " process", facts["process"]["result"], b, mobile)

            # -- capabilities: orbital layout of implemented routes -------------
            items = facts["integrations"]["items"]
            h = 270 + len(items) * 125 if mobile else 600
            b = txt(28 if mobile else 44, 44, "CAPABILITIES / CONNECTIONS", 13, "muted") + para(
                28 if mobile else 44,
                84,
                facts["integrations"]["title"],
                344 if mobile else 900,
                25 if mobile else 30,
                "ink",
                2,
            )
            if mobile:
                b += (
                    '<ellipse cx="200" cy="203" rx="132" ry="53" fill="none" stroke="'
                    f'{p["line"]}"/><circle cx="200" cy="203" r="43" fill="{p["panel"]}" '
                    f'stroke="{p["primary"]}"/>'
                ) + txt(200, 213, name[:2].upper(), 28, "primary", "middle", 700)
                for i, item in enumerate(items):
                    b += card(28, 278 + i * 125, 344, item["title"], item["detail"], 112)
            else:
                b += (
                    '<ellipse cx="500" cy="337" rx="238" ry="176" fill="none" stroke="'
                    f'{p["line"]}"/><ellipse cx="500" cy="337" rx="193" ry="144" fill="none" '
                    f'stroke="{p["line"]}" stroke-dasharray="2 9"/><circle cx="500" cy="337" '
                    f'r="68" fill="{p["panel"]}" stroke="{p["primary"]}"/>'
                ) + txt(500, 348, name[:2].upper(), 34, "primary", "middle", 700)
                for i, item in enumerate(items):
                    side = i % 2
                    y = 156 + (i // 2) * 146
                    x = 40 if side == 0 else 724
                    b += line(
                        f"M{(276 if side == 0 else 568)} {(y + 55 if side == 0 else 337)}H"
                        f"{(390 if side == 0 else 662)}V{(337 if side == 0 else y + 55)}H"
                        f"{(432 if side == 0 else 724)}"
                    )
                    b += card(x, y, 236, item["title"], item["detail"], 112)
            save("integrations", w, h, name + " integration routes",
                 facts["integrations"]["title"], b, mobile)

    for mode in ["dark", "light"]:
        render_mode(mode)
    render_site_artwork(repo, palette)
    print(name, palette["id"], "SVG groups generated")


if __name__ == "__main__":
    render(Path(__file__).resolve().parent.parent)
